import type { FireData } from '@/data/fireSchema';
import { DEVELOPMENT_FIXTURE, warningText } from '@/data/fireWarnings';
import { formatShare, UNAVAILABLE } from '../../domain/fire/fireSummary';
import { type ForecastStatus } from '../../domain/fire/growthForecast';
import styles from './FireResults.module.css';

export function FireResultDetails({
  data,
  forecast,
}: {
  data: FireData;
  forecast: ForecastStatus;
}) {
  const { result } = data;
  const { nisar, sentinel1, sentinel2, summer } = result.satellite_images;
  const grid = result.map_grid;
  const model = result.model_result;
  const fixture = result.warnings.includes(DEVELOPMENT_FIXTURE);
  const source = result.neighbour_forest?.source.trim().toLowerCase();
  return (
    <details className={styles.details}>
      <summary>Details: metadata, method, warnings and sources</summary>
      <h5 className={styles.subheading}>Metadata</h5>
      <dl className={styles.meta}>
        <dt>Fire id</dt>
        <dd>{result.fire.id}</dd>
        <dt>Model</dt>
        <dd>
          {model.model_version} · {model.region}
        </dd>
        <dt>Grid</dt>
        <dd>
          {grid.columns} × {grid.rows} cells · {grid.cell_size_m} m
        </dd>
        <dt>Observation summer</dt>
        <dd>{summer} · July–August</dd>
        <dt>NISAR L-band</dt>
        <dd>
          {nisar
            ? `${nisar.date}${nisar.fire_covered != null ? ` · ${formatShare(nisar.fire_covered)} of the fire covered` : ''}`
            : UNAVAILABLE}
        </dd>
        <dt>Sentinel-1 C-band</dt>
        <dd>
          {sentinel1
            ? `${sentinel1.from} → ${sentinel1.to} · ${sentinel1.scenes} scenes`
            : UNAVAILABLE}
        </dd>
        <dt>Sentinel-2 optical</dt>
        <dd>{sentinel2 ? `${sentinel2.from} → ${sentinel2.to}` : UNAVAILABLE}</dd>
        <dt>GEDI coordinates</dt>
        <dd>{result.lidar_points.length} supplied</dd>
      </dl>

      <h5 className={styles.subheading}>Method</h5>
      {fixture && (
        <p>
          This development fixture contains no model output. The method below is what real exports
          will follow.
        </p>
      )}
      <p>
        Recovery is the modelled canopy height as a share of the neighbouring forest’s height. The
        model combines NISAR and Sentinel-1 radar with Sentinel-2 optical imagery from one summer.
        Its validated error is the reported difference from GEDI lidar on fires it did not see in
        training.
      </p>
      <p>
        The grid’s relative-score layer bands the model’s score for forest above 5 m into Low,
        Medium and High. The score ranks cells but is not a calibrated probability. Grey cells mark
        the model’s geographic domain, which is a separate pipeline flag, not a score.
      </p>
      <p>
        {forecast.status === 'valid'
          ? `Forecast: method “saturating_exp”, r(age) = 1 − exp(−age / τ) with τ = ${forecast.curve.tau} years. The app draws it only because it reproduces the supplied years to 80% and 80% year. Ages outside ${forecast.curve.reliableAge[0]}–${forecast.curve.reliableAge[1]} are extrapolation.`
          : forecast.status === 'unsupported'
            ? `Forecast: ${forecast.reason}`
            : 'No growth forecast is supplied for this fire.'}
      </p>

      <h5 className={styles.subheading}>Warnings</h5>
      {result.warnings.length === 0 ? (
        <p>None supplied.</p>
      ) : (
        <ul className={styles.list}>
          {result.warnings.map((w) => (
            <li key={w}>
              {warningText(w)} <span className="font-mono text-xs">({w})</span>
            </li>
          ))}
        </ul>
      )}

      <h5 className={styles.subheading}>Sources</h5>
      <ul className={styles.list}>
        {fixture && (
          <li>Development fixture generated by scripts/build-dev-fixtures.ts: no observations.</li>
        )}
        {nisar && <li>NASA-ISRO NISAR L-band SAR</li>}
        {sentinel1 && <li>ESA Copernicus Sentinel-1 C-band SAR</li>}
        {sentinel2 && <li>ESA Copernicus Sentinel-2 MSI optical</li>}
        {(result.lidar_points.length > 0 || source === 'gedi') && <li>NASA GEDI lidar</li>}
        {source === 'eth' && <li>ETH Zürich Global Canopy Height (approximate)</li>}
        {result.fire.perimeter && <li>Fire perimeter and area: as supplied in result.json</li>}
        <li>Basemap: NASA GIBS Blue Marble, Natural Earth land, OpenFreeMap vector tiles</li>
      </ul>
    </details>
  );
}
